export const CHAT_POOLS=Object.fromEntries(Object.entries(pools).map(([context,lines])=>[context,lines.map((text,i)=>({id:`${context}:${i}`,text}))]));
export function chatContext(event,selected,result,module){
  if(event.kind==='leak')return result.kind==='reveal'?'leak_early':'leak_partial';
  if(event.kind==='reveal')return 'outfit_reveal';
  if(event.kind==='calendar')return event.celebrationType==='birthday'?'birthday':'anniversary';
  if(selected.postpone||selected.id==='later')return 'postpone';
  if(event.kind==='promise')return 'promise';
  if(event.kind==='project')return ['project_plan','project_pilot','project_review'][event.projectStep];
  if(event.kind==='finale')return 'finale';
  if(event.kind==='routine')return 'routine';
  if(event.kind==='match')return selected.id==='withdraw'?'module_finish':module?.matches.at(-1)?.won?'match_win':'match_loss';
  if(event.kind==='module')return module?.phase==='closed'?'module_finish':['orientation','working'].includes(module?.phase)&&module?.participation<=2?'module_intro':'module_work';
  if(/다음|미루|보류/.test(selected.text))return 'postpone';
  if(/잡담/.test(selected.text))return 'talk_switch';
  if(/대체|전환|다른 코너/.test(selected.text))return 'tech_alternative';
  const id=event.definitionId||'';
  if(['CE-001','CE-002','CE-003','CE-004','CE-005','CE-006','CE-010','RK-002','RK-003','RK-017','RK-025','RK-026','RK-027'].includes(id))return 'tech_check';
  if(['CE-036','RA-003'].includes(id))return 'waiting';
  if(['CE-015','CE-063','RK-013'].includes(id))return 'poll';
  if(['CE-013','CE-016','CE-056','CE-062','RK-011'].includes(id))return 'question';
  if(['CE-014','CE-059','CE-061','RK-009','RK-018'].includes(id))return 'fan_art';
  if(['CE-021','RK-022'].includes(id))return 'puzzle';
  if(id==='CE-020')return 'game_mistake';
  if(['CE-019','CE-022','CE-023','CE-024','RK-007','RK-010','RA-004'].includes(id))return 'game_practice';
  return 'general';
}
